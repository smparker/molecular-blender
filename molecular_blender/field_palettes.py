PALETTES = (('default', 'Field Default', 'Red–white–blue for signed fields, white–blue for unsigned fields'),
            ('viridis', 'Viridis', 'Sequential purple, green and yellow'),
            ('magma', 'Magma', 'Sequential near-black, purple, orange and pale yellow'))
KEEP_PALETTE = ('current', 'Current Ramp', 'Keep the current editable colors')


def apply_palette(node, preset, kind, low, high):
    def linear(x):
        return x/12.92 if x <= .04045 else ((x+.055)/1.055)**2.4

    if preset in ('viridis', 'magma'):
        table = VIRIDIS if preset == 'viridis' else MAGMA
        stops = [(i/255, (linear(r), linear(g), linear(b), 1.)) for i, r, g, b in table]
        node.label = preset.title()
    elif preset == 'default':
        stops = [(0., (1., 1., 1., 1.)), (1., (.025, .12, .85, 1.))]
        node.label = 'Low to high'
        if kind != 'unsigned':
            stops[0] = (0., (.8, .025, .015, 1.))
            stops.insert(1, (-low/(high-low), (1., 1., 1., 1.)))
            node.label = 'Negative · zero · positive'
    else:
        raise ValueError('Unknown color palette')
    node['mb_anchor_zero'] = preset == 'default' and kind != 'unsigned'
    ramp = node.color_ramp
    ramp.color_mode = 'RGB'
    ramp.interpolation = 'LINEAR'
    while len(ramp.elements) > 1:
        ramp.elements.remove(ramp.elements[-1])
    for index, (position, color) in enumerate(stops):
        stop = ramp.elements.new(position) if index else ramp.elements[0]
        stop.position, stop.color = position, color
